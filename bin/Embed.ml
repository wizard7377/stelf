(* Turns a directory of template files into an OCaml module that carries them
   as (relative path, contents) pairs.

   This runs at build time, from the rule in [bin/dune], so [stelf setup] stays
   a single self-contained binary with nothing to locate on disk at run time.
   The point of the indirection is that the template files are real files:
   editable, diffable, and checkable by whatever tool understands their format,
   rather than string literals that only the OCaml compiler ever looks at. *)

let read path =
  let ic = open_in_bin path in
  Fun.protect
    ~finally:(fun () -> close_in ic)
    (fun () -> really_input_string ic (in_channel_length ic))

(* Paths arrive prefixed with the template root, which is an artefact of where
   the sources happen to sit and must not reach the generated project. *)
let strip_root ~root path =
  let n = String.length root in
  if String.length path > n && String.sub path 0 n = root then
    match path.[n] with
    | '/' | '\\' -> String.sub path (n + 1) (String.length path - n - 1)
    | _ -> path
  else path

let () =
  let root = Sys.argv.(1) in
  let paths =
    Array.to_list (Array.sub Sys.argv 2 (Array.length Sys.argv - 2))
  in
  print_string
    "(* Generated by Embed.ml from bin/templates/ -- do not edit. *)\n\n\
     let files : (string * string) list =\n\
    \  [\n";
  List.iter
    (fun path ->
      Printf.printf "    (%S, %S);\n" (strip_root ~root path) (read path))
    paths;
  print_string "  ]\n"
