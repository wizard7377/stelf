let[@inline] calc_over : 'a. ('a -> int * int * int -> 'a) -> 'a -> 'a =
 fun f x ->
  List.fold_left
    (fun acc row -> List.fold_left (fun acc' cell -> f acc' cell) acc row)
    x logo_values

let[@inline] calc_over_pos : 'a. ('a -> int * int * int -> 'a) -> 'a -> 'a =
 fun f x ->
  List.fold_left
    (fun acc row ->
      List.fold_left
        (fun acc' cell -> if cell != (0, 0, 0) then f acc' cell else acc')
        acc row)
    x logo_values

let true_peak : int =
  calc_over_pos
    (fun acc (r, g, b) ->
      let v = r + g + b in
      if v > acc then v else acc)
    0

let true_avg : float =
  calc_over_pos
    (fun acc (r, g, b) ->
      let v = float_of_int (r + g + b) in
      acc +. v)
    0.0
  /. float_of_int 421

let log_base : float -> float -> float = fun x y -> Float.log x /. Float.log y

let true_value : int -> float =
 fun x ->
  log_base (float_of_int x) true_avg
  /. log_base (float_of_int true_peak) true_avg
