  if Stdlib.( < ) (r + g + b) 10 then string " "
  else
    Style.Fore.rgb (amplify r) (amplify g) (amplify b)
    @@ string @@ Stdlib.String.of_char
    @@ fill_chars_nth (light r g b)

(* [Display.nl] is Format.pp_print_newline, which RESETS the pretty-printer —
   closing every open box and flushing the device — rather than breaking a line.
   A logo is a grid of rows, so use the primitive that actually means "break
   here, keep the boxes": otherwise this form destroys any enclosing box, e.g.
   the [@[<v>%t@]] wrapper in src/Fronts/Tui/Repl.ml, and forces 24 flushes. *)
let row_break : form = fun ppf -> Format.pp_force_newline ppf ()

let[@inline] cells (f : form list list) : form =
  concat ~sep:row_break (List.map (fun row -> concat ~sep:empty row) f)

let logo : form =
  cells (List.map (List.map (fun (r, g, b) -> colored r g b)) logo_values)
