(* The art data in [logo_values] below is stored in a compressed range: over all
   421 non-zero cells the componentwise maxima are (15, 78, 68). Read as 0-255
   sRGB that is a very dark teal, and most cells are near black — so the logo
   would still be invisible even with Display's Style vocabulary working. Every
   channel is scaled by 255/peak on the way to the terminal, which preserves hue
   (one factor for all three channels) and saturates the brightest cell.

   [peak] is the single knob for the logo's brightness: lower it to burn out more
   cells, raise it to dim. The grid in [logo_values] never changes. *)
let peak = 78
let peak_total = 150
let fill_chars = ".:*"

let[@inline] fill_chars_nth (l : float) =
  let n =
    Float.to_int @@ Float.round (float_of_int (String.length fill_chars) *. l)
  in
  let n' =
    if n < 0 then 0
    else if n >= String.length fill_chars then String.length fill_chars - 1
    else n
  in
  fill_chars.[n']

let[@inline] amplify (v : int) : int = Stdlib.min 255 (v * 255 / peak)

let[@inline] light (r : int) (g : int) (b : int) : float =
  let chan x = Stdlib.(float_of_int x /. float_of_int peak_total) in
  let v = chan r +. chan g +. chan b in
  if v < 0.0 then 0.0 else if v > 1.0 then 1.0 else v

